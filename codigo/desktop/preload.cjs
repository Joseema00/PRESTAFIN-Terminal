const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('prestafin', Object.freeze({
  workspaceIdentity: () => ipcRenderer.invoke('workspace:identity'),
  confirmReloadWorkspace: () => ipcRenderer.invoke('workspace:confirmReload'),
  recoverLegacyWorkspace: owner => ipcRenderer.invoke('workspace:recoverLegacy',owner),
  loadWorkspace: owner => ipcRenderer.invoke('workspace:load',owner),
  saveWorkspace: (value,owner) => ipcRenderer.invoke('workspace:save',value,owner),
  exportWorkspace: () => ipcRenderer.invoke('workspace:export'),
  importWorkspace: owner => ipcRenderer.invoke('workspace:import',owner),
  marketBundle: value => ipcRenderer.invoke('market:bundle',value),
  marketSearch: query => ipcRenderer.invoke('market:search',query),
  fundLookup: isin => ipcRenderer.invoke('market:fundLookup',isin),
  fundList: () => ipcRenderer.invoke('market:fundList'),
  fundHistory: value => ipcRenderer.invoke('market:fundHistory',value),
  billingStatus: () => ipcRenderer.invoke('billing:status'),
  billingRedeemCode: code => ipcRenderer.invoke('billing:redeemCode',code),
  authSignIn: (email,password) => ipcRenderer.invoke('auth:signIn',email,password),
  authSignUp: (email,password) => ipcRenderer.invoke('auth:signUp',email,password),
  authConfirmEmail: (email,proof) => ipcRenderer.invoke('auth:confirmEmail',email,proof),
  authResendConfirmation: email => ipcRenderer.invoke('auth:resendConfirmation',email),
  authRequestPasswordReset: email => ipcRenderer.invoke('auth:requestPasswordReset',email),
  authResetPassword: (email,proof,password) => ipcRenderer.invoke('auth:resetPassword',email,proof,password),
  billingCheckout: plan => ipcRenderer.invoke('billing:checkout',plan),
  billingPortal: () => ipcRenderer.invoke('billing:portal'),
  billingLogout: () => ipcRenderer.invoke('billing:logout'),
  appInfo: () => ipcRenderer.invoke('app:info'),
}));
